// ==, ===

// >, <, >=, <=

let a = 10;

let b = 15;

console.log(a>b);
console.log(a>=b);
console.log(a<b);
console.log(a<=b);

// === Strict check will check for both the datatype and values are same
// == lose check will check for either value or datatype

console.log(5 == "5");

console.log(5 !== "5");

console.log("Anas" === "Anas");

console.log("Anas" !== "Anas");