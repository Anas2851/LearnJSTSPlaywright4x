// Literals are the value assigned to a variable.

let a = 10;

//Here 10 is a literal value assigned to the variable 'a'.

// There are different types of literals in JavaScript:

// 1. Numeric Literals
let num = 42; // 42 is a numeric literal

let p = 3.14; //3.14 is a numeric literal

// 2. String Literals
let str = "Hello, World!"; // "Hello, World!" is a string literal

// 3. Boolean Literals
let isTrue = true; // true is a boolean literal
let isFalse = false; // false is a boolean literal

// 4. Null Literal
let nullValue = null; // null is a null literal

// 5. Undefined Literal
let undefined; // undefined is an undefined literal

console.log(typeof nullValue);
console.log(typeof isTrue);
console.log(typeof p);
console.log(typeof num);
console.log(typeof str);
console.log(typeof undefined);
